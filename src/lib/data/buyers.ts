/** Builds a plausible status history up to `stage`, ending at `last`. */
function history(stage: RequirementStage, start: string, stepDays = 6): StatusEvent[] {
  const idx = REQUIREMENT_STAGES.indexOf(stage);
  const t0 = new Date(start + "T10:00:00+05:30").getTime();
  return REQUIREMENT_STAGES.slice(0, idx + 1).map((s, i) => ({
    stage: s,
    at: new Date(t0 + i * stepDays * 86400000 + i * 3600000 * 3).toISOString(),
    by: s === "submitted" ? "buyer" : STAGE_BY[s],
    note: STAGE_NOTE[s],
  }));
}

